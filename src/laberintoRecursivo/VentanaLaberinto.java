    private void btnResolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResolverActionPerformed
        if (timer != null && timer.isRunning()) return;

        tablero.limpiarMarcas();
        Laberinto lab = tablero.getLaberinto();

        // 1. La recursividad genera TODA la secuencia de exploración
        encontrada = lab.resolver();
        pasos = lab.getPasos();
        indice = 0;

        // 2. El temporizador la reproduce paso a paso
        int retardo = 520 - 5 * sldVelocidad.getValue();
        btnResolver.setEnabled(false);
        lblEstado.setText("Explorando...");

        timer = new Timer(retardo, e -> {
            if (indice < pasos.size()) {
                tablero.aplicarPaso(pasos.get(indice++));
            } else {
                timer.stop();
                btnResolver.setEnabled(true);
                String msg = encontrada ? "¡Se encontró la salida!"
                                        : "No existe un camino posible.";
                lblEstado.setText(msg);
                JOptionPane.showMessageDialog(this, msg);
            }
        });
        timer.start();
    }//GEN-LAST:event_btnResolverActionPerformed

